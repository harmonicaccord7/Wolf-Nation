import {test,expect} from '@playwright/test'
import fs from 'node:fs/promises'
test('Country share review separates historical ratios from assumed future dividends',async({page,isMobile},info)=>{
  await page.goto('/africa/cameroon')
  await page.getByRole('link',{name:'Review a share or IPO',exact:true}).click()
  await expect(page).toHaveURL(/\/africa\/share-review\?country=cameroon$/)
  await expect(page.getByRole('heading',{name:'Africa Share & IPO Review',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Load a hypothetical example',exact:true}).click()
  await expect(page.getByText(/^HYPOTHETICAL EXAMPLE —/)).toBeVisible()
  const ratios=page.getByLabel('Entered company ratios',{exact:true})
  await expect(ratios).toContainText('12.50×')
  await expect(ratios).toContainText('4.00%')
  await expect(page.getByLabel('Assumed dividend per share during this scenario (XAF)',{exact:true})).toHaveValue('0')
  const positions=page.getByLabel('Share position results',{exact:true})
  await expect(positions).toContainText('99')
  await expect(positions).toContainText('99,990 XAF')
  const selected=page.getByRole('table',{name:'Share price scenarios'}).getByRole('row').filter({hasText:'selected'})
  await expect(selected).toContainText('117,622 XAF')
  await page.getByLabel('Assumed dividend per share during this scenario (XAF)',{exact:true}).fill('40')
  await expect(selected).toContainText('121,582 XAF')
  await page.getByLabel('Shares per trading lot',{exact:true}).fill('100')
  await expect(positions).toContainText('0 full trading lots')
  await expect(page.getByText(/cannot buy one full lot/)).toBeVisible()
  if(isMobile)await page.setViewportSize({width:844,height:390})
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  await info.attach('africa-share-review',{body:await page.getByRole('table',{name:'Share price scenarios'}).screenshot({scale:'css'}),contentType:'image/png'})
})
test('Missing accounts remain unavailable and invalid assumptions withhold export',async({page,request})=>{
  await page.goto('/africa/share-review?country=botswana')
  await page.getByRole('button',{name:'Load a hypothetical example',exact:true}).click()
  await page.getByLabel('Past annual earnings per share (EPS) (BWP)',{exact:true}).fill('-80')
  const ratios=page.getByLabel('Entered company ratios',{exact:true})
  await expect(ratios.locator('article').filter({has:page.locator('b',{hasText:/^P\/E$/})})).toContainText('Not available')
  await page.getByLabel('Past annual dividend per share (BWP)',{exact:true}).fill('')
  await expect(ratios.locator('article').filter({hasText:'Past dividend yield'})).toContainText('Not available')
  await page.getByLabel('Assumed share price change (%)',{exact:true}).fill('-101')
  await expect(page.getByRole('alert')).toContainText('−100%')
  await expect(page.getByRole('button',{name:'Download share review CSV'})).toBeDisabled()
  expect((await request.get('/africa/share-review?country=not-a-country')).status()).toBe(404)
  expect((await request.get('/africa/share-review?country=cameroon&country=botswana')).status()).toBe(404)
  const sitemap=await request.get('/sitemap.xml')
  expect(await sitemap.text()).toContain('https://www.kaporalintelligence.com/africa/share-review')
  await page.goto('/search?q=share')
  await expect(page.getByRole('link',{name:/Africa Share & IPO Review/})).toBeVisible()
})
test('Country changes clear figures and a local CSV protects notes without posting inputs',async({page})=>{
  const posts:string[]=[]
  page.on('request',request=>{if(request.method()==='POST')posts.push(request.url())})
  await page.goto('/africa/share-review?country=cameroon')
  await page.getByRole('button',{name:'Load a hypothetical example',exact:true}).click()
  await page.getByLabel('Country / currency',{exact:true}).selectOption('botswana')
  await expect(page.getByLabel('Share / offer price (BWP)',{exact:true})).toHaveValue('')
  await expect(page.getByLabel('Company / security name',{exact:true})).toHaveValue('')
  await expect(page.getByRole('status').first()).toContainText('All figures were cleared')
  await page.getByRole('button',{name:'Load a hypothetical example',exact:true}).click()
  await page.getByLabel('Company / security name',{exact:true}).fill('=1+1')
  const downloadPromise=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download share review CSV',exact:true}).click()
  const download=await downloadPromise,path=await download.path()
  expect(path).not.toBeNull()
  const csv=await fs.readFile(path!,'utf8')
  expect(csv).toContain('"company","\'=1+1"')
  expect(csv).toContain('"currency","BWP"')
  expect(csv).toContain('"price_document_date","Not entered"')
  expect(csv).toContain('africa-share-review-1.0')
  expect(posts).toEqual([])
})
