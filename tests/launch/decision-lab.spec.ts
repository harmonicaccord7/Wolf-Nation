import { test, expect } from '@playwright/test'
test('Decision Lab calculates editable outcomes, prevents invalid input and exports assumptions', async ({ page, isMobile }, info) => {
  await page.goto('/tools/decision-lab')
  await page.getByLabel('Asset', {exact:true}).selectOption('CUSTOM')
  for(const [label,value] of [['Reference price (USD)','100'],['Cash budget (USD)','1000'],['Fee per transaction (%)','0'],['Second-stage price (USD)','100'],['Option strike (USD)','100'],['Option premium per unit (USD)','5'],['Units per option contract','100']]) await page.getByLabel(label,{exact:true}).fill(value)
  await page.getByRole('button',{name:'+20%',exact:true}).click()
  const table=page.getByRole('table',{name:'Decision comparison'})
  await expect(table.getByRole('row').filter({has:page.getByRole('rowheader',{name:'● Buy now',exact:true})})).toContainText('+$200.00')
  await expect(table.getByRole('row').filter({has:page.getByRole('rowheader',{name:/Buy a call/})})).toContainText('+$3,000.00')
  await page.getByRole('button',{name:'-20%',exact:true}).click()
  await expect(table.getByRole('row').filter({has:page.getByRole('rowheader',{name:/Buy a put/})})).toContainText('+$3,000.00')
  await page.getByLabel('Cash budget (USD)',{exact:true}).fill('499')
  await expect(table).toContainText('Budget cannot buy one contract')
  await page.getByLabel('Cash budget (USD)',{exact:true}).fill('')
  await expect(page.locator('section.liveSection').getByRole('alert')).toContainText('Enter a number')
  await expect(table).toHaveCount(0)
  await page.getByLabel('Cash budget (USD)',{exact:true}).fill('1000')
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download this scenario',exact:true}).click()
  expect((await download).suggestedFilename()).toBe('kaporal-decision-scenario.csv')
  if(isMobile)await page.setViewportSize({width:844,height:390})
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  await info.attach('decision-lab-scenario',{body:await page.screenshot({fullPage:true,scale:'css'}),contentType:'image/png'})
})
test('Bitcoin coverage cards open the relevant evidence instead of acting like static tabs',async({page})=>{
  await page.goto('/bitcoin')
  const coverage=page.locator('.coverageCards')
  await expect(coverage.getByRole('link')).toHaveCount(6)
  await coverage.getByRole('link',{name:/ETF flows/}).click()
  await expect(page).toHaveURL(/\/data\/btc_etf_flow$/)
  await expect(page.getByRole('heading',{level:1})).toContainText('ETF')
})
