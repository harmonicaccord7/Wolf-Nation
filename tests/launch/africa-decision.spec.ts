import {test,expect} from '@playwright/test'
test('Homepage country pills and green metrics open country evidence and the currency tool',async({page,isMobile},info)=>{
  await page.goto('/')
  const countries=page.getByRole('navigation',{name:'Homepage Africa countries'})
  await expect(countries.getByRole('link')).toHaveCount(9)
  await expect(page.locator('.africaVisual a.afStat')).toHaveCount(4)
  await countries.getByRole('link',{name:'Cameroon',exact:true}).click()
  await expect(page).toHaveURL(/\/africa\/cameroon$/)
  await expect(page.getByRole('heading',{name:'Cameroon',exact:true})).toBeVisible()
  await expect(page.locator('.liveMetricGrid')).toContainText('World Bank')
  await expect(page.locator('#currency-lab')).toContainText('annual average')
  await page.getByLabel('Starting budget (USD)',{exact:true}).fill('1000')
  await page.getByLabel('Entry exchange rate (local units per USD)',{exact:true}).fill('600')
  await page.getByLabel('Exit exchange rate (local units per USD)',{exact:true}).fill('720')
  await page.getByLabel('Total local-currency return (%)',{exact:true}).fill('10')
  await page.getByLabel('Annual inflation assumption (%)',{exact:true}).fill('5')
  await page.getByLabel('Conversion fee each way (%)',{exact:true}).fill('0')
  await expect(page.locator('[aria-label="Currency scenario results"]')).toContainText('916.67 USD')
  await expect(page.locator('[aria-label="Currency scenario results"]')).toContainText('+4.76%')
  await page.getByLabel('Exit exchange rate (local units per USD)',{exact:true}).fill('0')
  await expect(page.locator('#currency-lab').getByRole('alert')).toContainText('positive')
  await page.getByLabel('Exit exchange rate (local units per USD)',{exact:true}).fill('720')
  if(isMobile)await page.setViewportSize({width:844,height:390})
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  await info.attach('cameroon-currency-decision',{body:await page.locator('#currency-lab').screenshot({scale:'css'}),contentType:'image/png'})
})
test('Africa desk links every coverage card and Botswana has real source-labelled history',async({page,request})=>{
  await page.goto('/africa')
  await expect(page.locator('.coverageCards').getByRole('link')).toHaveCount(11)
  await page.locator('.coverageCards').getByRole('link',{name:/Botswana/}).click()
  await expect(page).toHaveURL(/\/africa\/botswana$/)
  await expect(page.locator('.liveMetricGrid')).toContainText('Botswana — GDP Growth')
  const response=await request.get('/api/intelligence/series/BWA_GDP_GROWTH?range=MAX')
  expect(response.status()).toBe(200);const data=await response.json();expect(data.frequency).toBe('annual');expect(data.history.length).toBeGreaterThanOrEqual(10)
  await page.getByRole('navigation',{name:'Africa country workspaces'}).getByRole('link',{name:'Nigeria',exact:true}).click()
  await expect(page.locator('#ipo-checklist')).toContainText('14 September 2026')
  await expect(page.locator('#ipo-checklist').getByRole('link',{name:/issuer/})).toHaveAttribute('href','https://ipo.dangote.com/')
  expect((await request.get('/africa/not-a-country')).status()).toBe(404)
})
